SMALL_DELTA = 5.0  # δ, мм (5–10 мм по методике; принят минимальный)


def bit_for(db_calc):
    return min(b for b in BITS if b >= db_calc)


def casing_for(di_min):
    """Наименьшая ОК, у которой есть исполнение с d ≥ di_min. Возвращает (D, допустимые (s,d))."""
    for D in sorted(OTTM):
        ok = [(s, d) for s, d in OTTM[D][2] if d >= di_min]
        if ok:
            return D, ok
    raise ValueError(di_min)


def russian_design():
    rows = []
    D = D_PROD
    names = ["Эксплуатационная", "Промежуточная", "Кондуктор"]
    depths = [PROD_DEPTH, INTER_DEPTH, COND_DEPTH]
    di_min = None
    for i, name in enumerate(names):
        if i > 0:
            D, ok = casing_for(di_min)
        else:
            ok = OTTM[D][2]
        nom, dm, _ = OTTM[D]
        dlt = delta_min(nom)
        db_calc = dm + 2 * dlt
        db = bit_for(db_calc)
        rows.append(dict(name=name, depth=depths[i], D=D, nom=nom, dm=dm, delta=dlt,
                         db_calc=db_calc, db=db, di_min_this=di_min, walls_ok=ok))
        di_min = db + 2 * SMALL_DELTA
    return rows


RU = russian_design()

