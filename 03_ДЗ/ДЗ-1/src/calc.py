def section_design(top, bot):
    """Интервалы, вскрытые при бурении секции: от башмака предыдущей колонны до bot.
    Возвращает требуемую плотность и окно совместимости."""
    subs = [s for s in SUB if s["bot"] > top and s["top"] < bot]
    rr = max(s["rr"] for s in subs)
    kf_max = max(s["kf"] for s in subs)
    kfr_min = min(s["kfr"] for s in subs)
    return dict(subs=subs, rr=rr, kf_max=kf_max, kfr_min=kfr_min,
                ok=kf_max < rr < kfr_min)


