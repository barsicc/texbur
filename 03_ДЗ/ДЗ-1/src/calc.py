def k_index(p_mpa, z):
    return p_mpa * 1e6 / (RHO_W * G * z)


def ks(z_top, z_bot):
    """Коэффициент безопасности: 1,1 при z < 1200 м, 1,05 при z > 1200 м."""
    return 1.1 if z_bot <= 1200 else 1.05


# Подынтервалы для ρR (граница 1200 м делит песчаник)
def subintervals():
    out = []
    for top, bot, rock, pf, pfr in LAYERS:
        kf, kfr = k_index(pf, bot), k_index(pfr, bot)
        cuts = [top, bot]
        if top < 1200 < bot:
            cuts = [top, 1200, bot]
        for a, b in zip(cuts, cuts[1:]):
            k = ks(a, b)
            out.append(dict(top=a, bot=b, rock=rock, pf=pf, pfr=pfr,
                            kf=kf, kfr=kfr, ks=k, rr=k * kf))
    return out


SUB = subintervals()

